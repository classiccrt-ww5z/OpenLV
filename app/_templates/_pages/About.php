    <h2 style="font-size: 19px; margin-bottom: 5px;">About LiiVid</h2>
    <p>Founded in April 2023 (Revived by a Community Member in November 2025), LiiVid is a consumer media website for people to watch and share original videos worldwide through a Web experience. LiiVid allows people to easily upload, tag, and share video clips on <a href="/">LiiVid.lol</a> and across the Internet through websites, blogs, and e-mail, as well as to build their own personal video network.</p>
    <p>Everyone can watch videos on LiiVid. People can see first-hand accounts of current events, find videos about their hobbies and interests, and discover the quirky and unusual. As more people capture special moments on video, LiiVid is empowering them to become the broadcasters of tomorrow.</p>
    <p>Inspired by a website originally launched by a college student, LiiVid was created to bring back the glory days of the old Internet, but with fresh new content.</p>
